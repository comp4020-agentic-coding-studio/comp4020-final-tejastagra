#!/usr/bin/env node
// Rebuilds docs/process-log.md from the commit history, oldest first.
// Each commit message carries Why, What, Harness and Prompt lines (see CLAUDE.md),
// so the log is a complete, step-by-step record of how the project was built.
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

const OUT = 'docs/process-log.md';
const KEYS = ['Why', 'What', 'Harness', 'Prompt'];
const RS = '\x1e';
const US = '\x1f';

function gitLog() {
  try {
    return execFileSync(
      'git',
      ['log', '--reverse', '--date=short', '--format=%H%x1f%h%x1f%ad%x1f%s%x1f%b%x1e'],
      { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'] },
    );
  } catch {
    return ''; // no commits yet
  }
}

// Commit links in the form scripts/check-evidence.ts verifies in PROCESS.md: [`abc1234`](url).
function commitBase() {
  try {
    const url = execFileSync('git', ['remote', 'get-url', 'origin'], {
      encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
    const m = url.match(/github\.com[:/](.+?)(\.git)?$/);
    return m ? `https://github.com/${m[1]}/commit/` : null;
  } catch {
    return null; // no remote yet
  }
}
const BASE = commitBase();
const cite = (short, hash) => (BASE ? `[\`${short}\`](${BASE}${hash})` : `\`${short}\``);

function parseBody(body) {
  const fields = {};
  const notes = [];
  let key = null;
  for (const line of body.split('\n')) {
    const ours = line.match(/^(Why|What|Harness|Prompt):\s*(.*)$/);
    if (ours) {
      key = ours[1];
      fields[key] = ours[2].trim();
      continue;
    }
    if (/^[A-Za-z][A-Za-z-]*:\s/.test(line)) {
      key = null; // another trailer, such as Co-Authored-By
      continue;
    }
    if (line.trim() === '') continue;
    if (key) fields[key] += ' ' + line.trim();
    else notes.push(line.trim());
  }
  return { fields, notes: notes.join(' ') };
}

const entries = gitLog()
  .split(RS)
  .map((r) => r.replace(/^\n+/, ''))
  .filter((r) => r.trim() !== '')
  .map((r) => {
    const [hash, short, date, subject, body = ''] = r.split(US);
    return { hash, short, date, subject, ...parseBody(body) };
  });

const out = [
  '# Process log',
  '',
  '> Generated by `scripts/process-log.mjs` from commit messages, oldest first. The pre-commit hook rebuilds and stages it, so each commit contains the log up to its parent. Run `pnpm log:process` for a copy that includes the latest commit. Commit links use the format that `pnpm check:evidence` verifies, so they can be copied straight into PROCESS.md. Do not edit by hand.',
  '',
  `Commits: ${entries.length}`,
  '',
];
entries.forEach((e, i) => {
  out.push(`## ${i + 1}. ${e.date}: ${e.subject}`, '');
  out.push(`- **Commit:** ${cite(e.short, e.hash)}`);
  for (const k of KEYS) out.push(`- **${k}:** ${e.fields[k] ?? '_missing_'}`);
  if (e.notes) out.push(`- **Notes:** ${e.notes}`);
  out.push('');
});

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, out.join('\n'));
console.log(`Wrote ${OUT} with ${entries.length} commits.`);
